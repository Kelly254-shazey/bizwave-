-- Opt-in business discovery. Only fields intentionally published by a business
-- can be seen by other authenticated businesses. Private operational records
-- remain subject to the existing tenant policies.
CREATE TABLE IF NOT EXISTS business_directory_profiles (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id UUID NOT NULL UNIQUE REFERENCES tenants(id) ON DELETE CASCADE,
  display_name VARCHAR(160) NOT NULL,
  sector VARCHAR(100) NOT NULL DEFAULT '',
  county VARCHAR(100) NOT NULL DEFAULT '',
  description VARCHAR(600) NOT NULL DEFAULT '',
  contact_email VARCHAR(255),
  website VARCHAR(500),
  is_published BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_business_directory_discover
  ON business_directory_profiles (lower(county), lower(sector)) WHERE is_published;

ALTER TABLE business_directory_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE business_directory_profiles FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS directory_select ON business_directory_profiles;
CREATE POLICY directory_select ON business_directory_profiles FOR SELECT
  USING (is_published OR tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid);
DROP POLICY IF EXISTS directory_insert ON business_directory_profiles;
CREATE POLICY directory_insert ON business_directory_profiles FOR INSERT
  WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid);
DROP POLICY IF EXISTS directory_update ON business_directory_profiles;
CREATE POLICY directory_update ON business_directory_profiles FOR UPDATE
  USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid)
  WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid);
DROP POLICY IF EXISTS directory_delete ON business_directory_profiles;
CREATE POLICY directory_delete ON business_directory_profiles FOR DELETE
  USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid);

-- A zero in the existing cost column does not tell us whether costs were
-- supplied. Record the provenance instead of treating missing costs as profit.
ALTER TABLE sales ADD COLUMN IF NOT EXISTS cost_basis VARCHAR(16) NOT NULL DEFAULT 'unknown';
DO $$ BEGIN
  ALTER TABLE sales ADD CONSTRAINT sales_cost_basis_check
    CHECK (cost_basis IN ('unknown', 'actual', 'estimated'));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
-- Earlier POS records used stored product costs; other historical costs may
-- have been generated by defaults and are deliberately left unknown.
UPDATE sales SET cost_basis = 'actual'
  WHERE cost_basis = 'unknown' AND source_system = 'portal_pos' AND cost_of_goods_sold > 0;

